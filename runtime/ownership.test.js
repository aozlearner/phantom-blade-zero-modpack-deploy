"use strict";
const assert=require('node:assert/strict'),{create}=require('./ownership');
const known=['One','Two'];
assert.throws(()=>create(['One','one']));
let r=create(known);
assert.throws(()=>r.register({id:'bad',outfits:[{id:'One'},{id:'unknown'}],prepare(){}}));
assert.equal(r.status().registered,0);
const calls=[],a={},b={};let blocked=false,beginFails=false;
const prepare=outfit=>({begin:actor=>{calls.push(['begin',outfit.id,actor]);if(beginFails)throw Error('render failed');},dispose:()=>{calls.push(['dispose',outfit.id]);return !blocked;}});
r.register({id:'provider',outfits:known.map(id=>({id})),prepare});r.seal();
assert.throws(()=>r.register({id:'late',outfits:[{id:'One'}],prepare}));
r.activate(a,'ONE');r.activate(b,'Two');
const n=calls.length;r.activate(a,'one');assert.equal(calls.length,n);
r.activate(a,'Two');assert.deepEqual(calls.slice(-2).map(x=>x.slice(0,2)),[['dispose','One'],['begin','Two']]);
assert.equal(r.current(b),'Two');
blocked=true;assert.throws(()=>r.activate(a,'One'));assert.equal(r.current(a),'Two');
blocked=false;r.activate(a,'original');assert.equal(r.current(a),undefined);
beginFails=true;assert.throws(()=>r.activate(a,'One'));assert.equal(r.current(a),undefined);
blocked=true;assert.throws(()=>r.activate(a,'One'));assert.equal(r.current(a),'One');
beginFails=false;assert.throws(()=>r.activate(a,'Two'));
assert.throws(()=>r.dispose());assert.equal(r.status().active,2);
blocked=false;r.dispose();r.dispose();assert.equal(r.status().active,0);
assert.throws(()=>r.activate(a,'One'));
r=create(known);r.register({id:'partial',outfits:[{id:'One'}],prepare});assert.throws(()=>r.seal());
console.log('Ownership: transactional registration, case conflicts, complete roster, cleanup ordering, per-actor isolation and retry after failures passed');
